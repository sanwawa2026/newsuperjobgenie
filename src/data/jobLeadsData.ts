/**
 * Parses CSV lines handling quoted values with embedded commas or newlines.
 */
export function parseCSVRow(text: string): string[] {
  const result: string[] = [];
  let cur = '';
  let inQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '"') {
      if (inQuotes && text[i + 1] === '"') {
        cur += '"';
        i++;
      } else {
        inQuotes = !inQuotes;
      }
    } else if (c === ',' && !inQuotes) {
      result.push(cur.trim());
      cur = '';
    } else {
      cur += c;
    }
  }
  result.push(cur.trim());
  return result;
}

/**
 * Parses exported SuperJobGenie Indeed CSV text into JobLeadCard objects.
 */
export function parseLeadsFromCSV(csvContent: string): JobLeadCard[] {
  if (!csvContent || !csvContent.trim()) return INITIAL_JOB_LEADS;

  const rawLines = csvContent.split(/\r?\n/);
  // Reconstruct lines if there are unclosed quotes
  const logicalRows: string[] = [];
  let buffer = '';
  let insideQuotes = false;

  for (const line of rawLines) {
    const quoteCount = (line.match(/"/g) || []).length;
    if (insideQuotes) {
      buffer += ' ' + line;
      if (quoteCount % 2 !== 0) {
        insideQuotes = false;
        logicalRows.push(buffer);
        buffer = '';
      }
    } else {
      if (quoteCount % 2 !== 0) {
        insideQuotes = true;
        buffer = line;
      } else if (line.trim()) {
        logicalRows.push(line);
      }
    }
  }

  if (buffer) logicalRows.push(buffer);
  if (logicalRows.length <= 1) return INITIAL_JOB_LEADS;

  const leads: JobLeadCard[] = [];
  // Skip header row
  for (let i = 1; i < logicalRows.length; i++) {
    const cols = parseCSVRow(logicalRows[i]);
    if (cols.length < 4) continue;

    const title = cols[0] || 'Software Engineer';
    const company = cols[1] || 'Company';
    const location = (cols[2] || 'California').replace(/\s+/g, ' ');
    const rawScore = parseInt(cols[3], 10);
    const matchScore = isNaN(rawScore) ? 85 : rawScore;
    const matchTier = cols[4] || (matchScore >= 90 ? 'Top 1% Exceptional' : 'Competitive Strong');
    const postingFreshness = cols[5] || 'Active Posting';
    const rawSkills = cols[6] || '';
    const jobUrl = cols[7] || 'https://www.indeed.com';
    const scannedDate = cols[8] || new Date().toISOString().split('T')[0];

    // Clean up skills string into array
    const skills = rawSkills
      .split(/[,;]/)
      .map(s => s.replace(/[…""]/g, '').trim())
      .filter(s => s.length > 2)
      .slice(0, 6);

    leads.push({
      id: `lead-parsed-${i}-${Date.now()}`,
      title,
      company,
      location,
      matchScore,
      matchTier,
      postingFreshness,
      keyMatchedSkills: skills.length > 0 ? skills : ['Full Stack Development', 'Cloud Architecture'],
      jobUrl,
      scannedDate
    });
  }

  return leads.length > 0 ? leads : INITIAL_JOB_LEADS;
}

/**
 * Generates a clean, presentation-ready 5-column CSV without 200-char URLs or messy quotes.
 */
export function generateClean5ColumnCSV(leads: JobLeadCard[]): string {
  const headers = ['Rank', 'Role Title', 'Company', 'Location', 'Match Score (%)', 'Tier', 'Key Verified Skills'];
  const rows = leads.map((lead, idx) => [
    `#${idx + 1}`,
    `"${lead.title.replace(/"/g, '""')}"`,
    `"${lead.company.replace(/"/g, '""')}"`,
    `"${lead.location.replace(/"/g, '""')}"`,
    `${lead.matchScore}%`,
    `"${lead.matchTier}"`,
    `"${lead.keyMatchedSkills.slice(0, 3).join(' • ').replace(/"/g, '""')}"`
  ]);

  return [headers.join(','), ...rows.map(r => r.join(','))].join('\n');
}

